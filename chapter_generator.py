def save_chapter(chapter_num, content):
    """保存章节到文件"""
    chapter_file = CHAPTERS_DIR / f"ch{chapter_num:03d}.md"
    with open(chapter_file, 'w', encoding='utf-8') as f:
        f.write(content)
    return chapter_file

def main():
    """主函数"""
    parser = argparse.ArgumentParser(description='网文小说章节生成器')
    parser.add_argument('--chapter', '-c', type=int, help='指定章节号')
    parser.add_argument('--auto', '-a', action='store_true', help='自动生成下一章')
    parser.add_argument('--list', '-l', action='store_true', help='列出所有已生成章节')
    
    args = parser.parse_args()
    
    if args.list:
        # 列出已生成章节
        if CHAPTERS_DIR.exists():
            chapters = list(CHAPTERS_DIR.glob("ch*.md"))
            print(f"已生成 {len(chapters)} 章：")
            for ch in sorted(chapters):
                print(f"  - {ch.stem}")
        else:
            print("暂无章节")
        return
    
    if args.auto:
        # 自动生成下一章
        chapter_num = get_chapter_number()
    elif args.chapter:
        chapter_num = args.chapter
    else:
        # 默认生成下一章
        chapter_num = get_chapter_number()
    
    print(f"正在生成第 {chapter_num} 章...")
    
    # 生成内容
    content = generate_chapter_content(chapter_num)
    
    # 保存章节
    chapter_file = save_chapter(chapter_num, content)
    print(f"✓ 章节已保存至：{chapter_file}")
    
    # 更新进度
    progress = load_progress()
    progress["current_chapter"] = chapter_num
    progress["last_generated"] = datetime.now().isoformat()
    progress["history"].append({
        "chapter": chapter_num,
        "file": str(chapter_file),
        "date": datetime.now().isoformat()
    })
    save_progress(progress)
    
    # 统计字数
    char_count = len(content)
    print(f"✓ 字数统计：{char_count} 字")
    print(f"✓ 完成进度：{chapter_num}/{progress['total_chapters']} ({chapter_num/progress['total_chapters']*100:.1f}%)")
    
    if chapter_num >= progress['total_chapters']:
        print("🎉 恭喜！全书已完成！")

if __name__ == "__main__":
    main()
